def fail(message: str) -> None:
    raise ValueError(message)


def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError as error:
        fail(f"cannot read {path}: {error}")


def load_toml(path: Path) -> dict[str, Any]:
    try:
        with path.open("rb") as stream:
            return tomllib.load(stream)
    except (OSError, tomllib.TOMLDecodeError) as error:
        fail(f"cannot parse {path}: {error}")


def load_metadata(root: Path, supplied: Path | None) -> dict[str, Any]:
    if supplied is not None:
        try:
            return json.loads(supplied.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as error:
            fail(f"cannot parse locked metadata {supplied}: {error}")
    try:
        output = subprocess.check_output(
            ["cargo", "metadata", "--locked", "--offline", "--format-version", "1"],
            cwd=root,
            text=True,
        )
        return json.loads(output)
    except (OSError, subprocess.CalledProcessError, json.JSONDecodeError) as error:
        fail(f"cannot load locked offline Cargo metadata: {error}")


def check_manifest(root: Path) -> None:
    if (root / "crates/transparent-uds-relay").exists():
        fail("obsolete transparent UDS relay crate is present")
    manifest = load_toml(root / "Cargo.toml")
    workspace = manifest.get("workspace")
    if not isinstance(workspace, dict):
        fail("Cargo.toml lacks [workspace]")
    expected_members = [".", "crates/access-flow-relay"]
    if workspace.get("members") != expected_members:
        fail("workspace members must include exactly the product and relay")
    if workspace.get("default-members") != expected_members:
        fail("workspace default-members must validate both the product and relay")
    workspace_package = workspace.get("package", {})
    if workspace_package.get("version") != PRODUCT_VERSION:
        fail(f"workspace package version must remain {PRODUCT_VERSION}")
    package = manifest.get("package")
    if not isinstance(package, dict):
        fail("Cargo.toml lacks [package]")
    if package.get("version") != {"workspace": True} or package.get("license") != "MIT":
        fail("product package must inherit the workspace version under MIT")
    if package.get("publish") is not False:
        fail("product package must remain non-publishable during the local candidate program")

    lock = load_toml(root / "Cargo.lock")
    lock_packages = lock.get("package")
    if not isinstance(lock_packages, list):
        fail("Cargo.lock lacks package records")
    for package_name in ("acl-proxy", "acl-proxy-access-flow-relay"):
        locked_product = [
            package for package in lock_packages if package.get("name") == package_name
        ]
        if len(locked_product) != 1 or locked_product[0].get("version") != PRODUCT_VERSION:
            fail(
                f"Cargo.lock must contain exactly one {package_name} "
                f"{PRODUCT_VERSION} package"
            )

    relay_manifest = load_toml(root / "crates/access-flow-relay/Cargo.toml")
    relay = relay_manifest.get("package")
    if (
        not isinstance(relay, dict)
        or relay.get("name") != "acl-proxy-access-flow-relay"
        or relay.get("version") != {"workspace": True}
    ):
        fail("Access Flow relay must inherit the workspace version")
    linux_dependencies = (
        relay_manifest.get("target", {})
        .get("cfg(target_os = \"linux\")", {})
        .get("dependencies", {})
    )
    if not isinstance(linux_dependencies, dict):
        fail("Access Flow relay lacks its Linux dependency table")
    for dependency in ("access-flow-relay", "access-flow-unix"):
        if dependency not in linux_dependencies:
            fail(f"Access Flow relay lacks shared {dependency} ownership")
    if "proxy-protocol-v2-codec" in linux_dependencies:
        fail("obsolete PROXY-v2 codec remains in the Access Flow relay")

    release_script = read_text(root / "scripts/release.mjs")
    if "acl-proxy-transparent-uds-relay" in release_script:
        fail("release script retains the obsolete relay artifact")
    if 'const REPO = "kcosr/acl-proxy-access-runtime";' not in release_script:
        fail("release script must target the authoritative ACL Proxy repository")
    if 'const RELEASE_REMOTE = "access-runtime";' not in release_script:
        fail("release script must push through the authoritative access-runtime remote")
    dependencies = manifest.get("dependencies")
    if not isinstance(dependencies, dict):
        fail("Cargo.toml lacks [dependencies]")
    if dependencies.get("compu-brotli-sys") != "=1.2.0":
        fail("compu-brotli-sys must remain a direct exact =1.2.0 dependency")
    if dependencies.get("http") != "=1.4.2":
        fail("http must remain an exact production =1.4.2 dependency")
    dev_dependencies = manifest.get("dev-dependencies")
    if not isinstance(dev_dependencies, dict) or dev_dependencies.get("h2") != "=0.4.15":
        fail("h2 must remain an exact development-only =0.4.15 dependency")

    expected_patch = {"crates-io": {"hyper": {"path": "../access-runtime/third_party/hyper"}}}
    if manifest.get("patch") != expected_patch:
        fail("Cargo.toml must contain only the exact product-root Hyper source redirect")
    if "replace" in manifest:
        fail("Cargo.toml must not contain [replace] source overrides")

    dependency_tables: list[tuple[str, dict[str, Any]]] = []
    for table_name in ("dependencies", "dev-dependencies", "build-dependencies"):
        table = manifest.get(table_name)
        if isinstance(table, dict):
            dependency_tables.append((table_name, table))
    targets = manifest.get("target")
    if isinstance(targets, dict):
        for target_name, target in targets.items():
            if not isinstance(target, dict):
                continue
            for table_name in ("dependencies", "dev-dependencies", "build-dependencies"):
                table = target.get(table_name)
                if isinstance(table, dict):
                    dependency_tables.append((f"target.{target_name}.{table_name}", table))
    for table_name, table in dependency_tables:
        for name, specification in table.items():
            package = specification.get("package") if isinstance(specification, dict) else None
            resolved_name = package or name
            if resolved_name in {"http-body", "http-body-util", "hyper", "hyper-util"}:
                fail(
                    "acl-proxy must not directly depend on private transport package "
                    f"{resolved_name} ({table_name}.{name})"
                )
            if resolved_name == "http" and (table_name != "dependencies" or name != "http"):
                fail("http must remain the canonical root production dependency")
            if (name == "h2" or package == "h2") and (
                table_name != "dev-dependencies" or name != "h2" or package is not None
            ):
                fail("h2 must remain the canonical root development-only dependency")


def check_transport_resolution(root: Path, metadata: dict[str, Any]) -> None:
    packages = metadata.get("packages")
    if not isinstance(packages, list):
        fail("locked metadata lacks package records")
    for name, (version, registry) in TRANSPORT_PACKAGES.items():
        matches = [package for package in packages if package.get("name") == name]
        if len(matches) != 1:
            fail(f"locked graph must resolve exactly one {name} package")
        package = matches[0]
        if package.get("version") != version:
            fail(f"locked graph resolves forbidden {name} version {package.get('version')!r}")
        source = package.get("source")
        if registry:
            if source != f"registry+{REGISTRY}":
                fail(f"locked {name} {version} must resolve from crates.io")
        elif source is not None:
            fail("locked Hyper 1.10.1 must be source-less and resolve from the runtime fork")

    product = [package for package in packages if package.get("name") == "acl-proxy"]
    if len(product) != 1 or not isinstance(product[0].get("manifest_path"), str):
        fail("locked metadata lacks one canonical acl-proxy manifest path")
    if product[0].get("version") != PRODUCT_VERSION:
        fail(f"locked metadata must resolve acl-proxy {PRODUCT_VERSION}")
    if product[0].get("publish") != []:
        fail("locked metadata must retain the acl-proxy publication guard")
    hyper = next(package for package in packages if package.get("name") == "hyper")
    manifest_path = hyper.get("manifest_path")
    if not isinstance(manifest_path, str):
        fail("locked Hyper 1.10.1 lacks its resolved manifest path")
    product_root = Path(product[0]["manifest_path"]).parent
    expected = (product_root.parent / "access-runtime" / "third_party" / "hyper" / "Cargo.toml").resolve()
    if Path(manifest_path).resolve() != expected:
        fail("locked Hyper 1.10.1 does not resolve to the canonical sibling runtime fork")

    lock = load_toml(root / "Cargo.lock")
    lock_packages = lock.get("package")
    if not isinstance(lock_packages, list):
        fail("Cargo.lock lacks package records")
    for name, (version, registry) in TRANSPORT_PACKAGES.items():
        matches = [package for package in lock_packages if package.get("name") == name]
        if len(matches) != 1 or matches[0].get("version") != version:
            fail(f"Cargo.lock must contain exactly one {name} {version} package")
        source = matches[0].get("source")
        if registry and source != f"registry+{REGISTRY}":
            fail(f"Cargo.lock {name} {version} must resolve from crates.io")
        if not registry and source is not None:
            fail("Cargo.lock Hyper 1.10.1 must be source-less")


def check_deny_policy(root: Path) -> None:
    policy = load_toml(root / "deny.toml")
    if set(policy) != {"licenses", "sources"}:
        fail("deny.toml must contain only licenses and sources policy")
    licenses = policy.get("licenses")
    if not isinstance(licenses, dict):
        fail("deny.toml lacks [licenses]")
    if licenses.get("confidence-threshold") != 0.93:
        fail("deny.toml license confidence threshold must be 0.93")
    allowed = licenses.get("allow")
    if not isinstance(allowed, list) or set(allowed) != ALLOWED_LICENSES:
        fail("deny.toml global license allow set changed")
    if "BSL-1.0" in allowed:
        fail("BSL-1.0 must not be globally allowed")
    exceptions = licenses.get("exceptions")
    expected = [
        {
            "name": "compu-brotli-sys",
            "version": "=1.2.0",
            "allow": ["BSL-1.0"],
        }
    ]
    if exceptions != expected:
        fail("deny.toml must have one exact compu-brotli-sys BSL-1.0 exception")
    sources = policy.get("sources")
    expected_sources = {
        "unknown-registry": "deny",
        "unknown-git": "deny",
        "allow-registry": [REGISTRY],
    }
    if sources != expected_sources:
        fail("deny.toml registry/source policy changed")


def direct_runtime_packages(metadata: dict[str, Any]) -> list[dict[str, Any]]:
    resolve = metadata.get("resolve")
    packages = metadata.get("packages")
    if not isinstance(resolve, dict) or not isinstance(packages, list):
        fail("locked metadata lacks resolve graph or packages")
    root_id = resolve.get("root")
    nodes = resolve.get("nodes")
    if not isinstance(root_id, str) or not isinstance(nodes, list):
        fail("locked metadata lacks the product root resolution")
    root_nodes = [node for node in nodes if node.get("id") == root_id]
    if len(root_nodes) != 1 or not isinstance(root_nodes[0].get("deps"), list):
        fail("locked metadata does not resolve exactly one product root")
    packages_by_id = {
        package.get("id"): package
        for package in packages
        if isinstance(package, dict) and isinstance(package.get("id"), str)
    }
    direct: dict[str, dict[str, Any]] = {}
    for dependency in root_nodes[0]["deps"]:
        if not isinstance(dependency, dict):
            fail("locked metadata contains an invalid direct dependency")
        kinds = dependency.get("dep_kinds")
        if not isinstance(kinds, list) or not any(
            isinstance(kind, dict) and kind.get("kind") is None for kind in kinds
        ):
            continue
        package_id = dependency.get("pkg")
        package = packages_by_id.get(package_id)
        if not isinstance(package, dict):
            fail(f"locked metadata lacks direct package {package_id}")
        source = package.get("source")
        if source is None:
            continue
        if not isinstance(source, str) or not source.startswith("registry+"):
            fail(f"direct runtime dependency has forbidden source: {package_id}")
        for field in ("name", "version", "license"):
            if not isinstance(package.get(field), str):
                fail(f"direct runtime dependency lacks declared {field}: {package_id}")
        direct[str(package_id)] = package
    return sorted(direct.values(), key=lambda package: package["name"])


def check_notices(root: Path, metadata: dict[str, Any]) -> None:
    notices = read_text(root / "THIRD_PARTY_NOTICES")
    for marker in (
        "compu-brotli-sys 1.2.0, BSL-1.0",
        "brotli 8.0.3, BSD-3-Clause AND MIT",
        "access-runtime` crates are MIT-licensed",
    ):
        if marker not in notices:
            fail(f"THIRD_PARTY_NOTICES lacks required marker: {marker}")
    if notices.count(BSL_TEXT) != 1:
        fail("THIRD_PARTY_NOTICES must contain one exact complete BSL-1.0 text")
    if notices.count(BROTLI_MIT_TEXT) != 1:
        fail("THIRD_PARTY_NOTICES must contain one exact Google Brotli MIT notice")
    if notices.count(DROPBOX_BSD_TEXT) != 1:
        fail("THIRD_PARTY_NOTICES must contain one exact Dropbox BSD-3-Clause notice")
    if notices.count(ZSTANDARD_BSD_TEXT) != 1:
        fail("THIRD_PARTY_NOTICES must contain one exact Zstandard BSD-3-Clause notice")
    if notices.count(HYPER_MIT_TEXT) != 1:
        fail("THIRD_PARTY_NOTICES must contain one exact Hyper MIT notice")

    heading = "The product directly uses the following third-party runtime crates:\n"
    section_start = notices.find(heading)
    section_end = notices.find("\ncompu-brotli-sys 1.2.0\n", section_start)
    if section_start < 0 or section_end < 0:
        fail("THIRD_PARTY_NOTICES lacks the bounded direct dependency section")
    actual_lines = [
        line
        for line in notices[section_start + len(heading) : section_end].splitlines()
        if line.startswith("- ")
    ]
    expected_lines = [
        f"- {package['name']} {package['version']}, {package['license']}"
        for package in direct_runtime_packages(metadata)
    ]
    if actual_lines != expected_lines:
        fail("THIRD_PARTY_NOTICES direct dependency inventory differs from locked metadata")

    lock = load_toml(root / "Cargo.lock")
    packages = lock.get("package")
    if not isinstance(packages, list):
        fail("Cargo.lock lacks package records")
    compu = [
        package
        for package in packages
        if package.get("name") == "compu-brotli-sys"
        and package.get("version") == "1.2.0"
    ]
    if len(compu) != 1 or not isinstance(compu[0].get("checksum"), str):
        fail("Cargo.lock lacks one checksummed compu-brotli-sys 1.2.0 record")
    checksum_marker = f"Cargo registry checksum:\n{compu[0]['checksum']}"
    if notices.count(checksum_marker) != 1:
        fail("compu-brotli-sys notice checksum differs from Cargo.lock")


def check_provenance(root: Path) -> None:
    provenance = read_text(root / "PROVENANCE.md")
    for marker in (
        PRODUCT_INITIAL_COMMIT,
        RUNTIME_COMMIT,
        "access-runtime/PROVENANCE.md",
        "compu-brotli-sys` 1.2.0",
        "Google Brotli C implementation it compiles is MIT",
        "Zstandard source under BSD-3-Clause",
    ):
        if marker not in provenance:
            fail(f"PROVENANCE.md lacks required marker: {marker}")
    if provenance.count(RUNTIME_COMMIT) != 1:
        fail("PROVENANCE.md must name the exact accepted runtime commit once")


def check_shipped_docs(root: Path) -> None:
    demos = root / "demos"
    if demos.exists() and any(path.is_file() or path.is_symlink() for path in demos.rglob("*")):
        fail("obsolete pre-schema-3 demos are present")
    readme = read_text(root / "README.md")
    normalized = " ".join(readme.split())
    if f"The `{PRODUCT_VERSION}` candidate requires `schema_version = 3`" not in normalized:
        fail("README lacks the exact strict-v3 candidate version marker")
    archive_inventory = (
        "Release archives contain `acl-proxy`, the capture-body extraction helper, "
        "this README, `LICENSE`, `THIRD_PARTY_NOTICES`, and "
        "`acl-proxy.sample.toml`. Linux archives also contain the Linux-only "
        "Access Flow relay."
    )
    if archive_inventory not in normalized:
        fail("README lacks the exact release archive inventory")
    archive_root = "acl-proxy-<version>-<acl12>/"
    required_layout = (
        archive_root,
        "  bin/acl-proxy",
        "  bin/acl-proxy-extract-capture-body",
        "  bin/acl-proxy-access-flow-relay  # Linux archives only",
        "  README.md",
        "  LICENSE",
        "  THIRD_PARTY_NOTICES",
        "  acl-proxy.sample.toml",
    )
    if any(entry not in readme for entry in required_layout):
        fail("README lacks the exact versioned release layout")
    platform_inventory = (
        "Linux archives have the three shown `bin/` entries; non-Linux archives "
        "omit the Linux-only relay and have the other two."
    )
    if platform_inventory not in normalized:
        fail("README lacks the platform-specific relay archive contract")
    if re.search(
        r"acl-proxy-[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?-[0-9a-f]{12}/",
        readme,
    ):
        fail("README hardcodes a future release SHA prefix")
    sample = read_text(root / "acl-proxy.sample.toml")
    for path, text in (("README.md", readme), ("acl-proxy.sample.toml", sample)):
        for obsolete in (
            "policy.external_auth_profiles",
            "policy.approval_macros",
            "external_auth_profile =",
            "[[policy.rules.header_actions]]",
        ):
            if obsolete in text:
                fail(f"{path} contains obsolete configuration surface: {obsolete}")
    if "schema_version = 3" not in sample:
        fail("sample configuration is not schema version 3")
    if "acl-proxy export-ca" not in sample:
        fail("sample configuration lacks generated public-CA export guidance")
    if "ca-cert.pem" in sample or "ca-key.pem" in sample:
        fail("sample configuration names obsolete generated CA storage files")
    packaging_gate = read_text(root / "scripts/check-packaging-policy.sh")
    audit_command = "cargo audit --no-fetch --no-yanked --deny warnings"
    deny_command = "cargo deny --locked --offline check -D warnings licenses sources"
    gate_lines = packaging_gate.splitlines()
    if gate_lines.count(audit_command) != 1:
        fail("packaging gate must run the exact offline advisory scan")
    if gate_lines.count(deny_command) != 1:
        fail("packaging gate must run the exact offline license and source scan")
    if gate_lines.index(deny_command) != gate_lines.index(audit_command) + 1:
        fail("packaging gate must run the advisory scan before the license and source scan")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--metadata", type=Path)
    args = parser.parse_args()
    root = args.root.resolve()
    try:
        check_manifest(root)
        check_deny_policy(root)
        metadata = load_metadata(root, args.metadata)
        check_transport_resolution(root, metadata)
        check_notices(root, metadata)
        check_provenance(root)
        check_shipped_docs(root)
    except ValueError as error:
        print(f"packaging policy check failed: {error}", file=sys.stderr)
        return 1
    print("product packaging, provenance, and notice policy passed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
